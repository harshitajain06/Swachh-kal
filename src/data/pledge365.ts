/** Days 361–365. */
export const PLEDGE_FINALE: string[] = [
  'Look back over your year. What are you proudest of?',
  'Say thank you to someone who helped you on this journey.',
  'Share your favourite Swachh habit with a new friend and invite them to take the pledge.',
  'Write a letter to your future self about the planet you want.',
  'You did it! Say the pledge out loud and celebrate: you are a Swachh Kal Eco Hero! Download your certificate.',
];

export const PLEDGE_DAYS = PLEDGE_MONTHS.reduce((n, m) => n + m.days.length, 0) + PLEDGE_FINALE.length;

export interface PledgeDay {
  day: number;
  text: string;
  /** Null during the celebration week. */
  month: PledgeMonth | null;
  monthNumber: number;
}

/** The prompt for a day number (1–365). */
export function pledgeDay(day: number): PledgeDay {
  const d = Math.min(PLEDGE_DAYS, Math.max(1, Math.floor(day)));
  const idx = d - 1;
  const monthIdx = Math.floor(idx / 30);
  if (monthIdx < PLEDGE_MONTHS.length) {
    const month = PLEDGE_MONTHS[monthIdx];
    return { day: d, text: month.days[idx % 30], month, monthNumber: monthIdx + 1 };
  }
  return { day: d, text: PLEDGE_FINALE[idx - PLEDGE_MONTHS.length * 30], month: null, monthNumber: 13 };
}
